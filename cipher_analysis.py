def analyze_cipher():
    print("=== Cipher Analysis ===")
    print(f"Total length: {len(encrypted_message)}")
    
    # Character frequency analysis
    char_freq = {}
    for char in encrypted_message:
        char_freq[char] = char_freq.get(char, 0) + 1
    
    print("\nCharacter frequency (top 20):")
    sorted_chars = sorted(char_freq.items(), key=lambda x: x[1], reverse=True)
    for char, freq in sorted_chars[:20]:
        print(f"'{char}': {freq}")
    
    # Look for patterns
    print("\nLooking for patterns...")
    
    # Check if it's a simple substitution cipher by looking at word patterns
    words = encrypted_message.split('^')
    print(f"Number of '^' separated segments: {len(words)}")
    
    # Look for repeated segments
    word_freq = {}
    for word in words:
        if word:  # Skip empty strings
            word_freq[word] = word_freq.get(word, 0) + 1
    
    print("\nRepeated segments:")
    for word, freq in sorted(word_freq.items(), key=lambda x: x[1], reverse=True):
        if freq > 1:
            print(f"'{word}': {freq} times")
    
    return words

def test_shift_cipher(text, shift):
    """Test if it's a simple Caesar cipher"""
    result = ""
    for char in text:
        if char.isalpha():
            base = ord('A') if char.isupper() else ord('a')
            result += chr((ord(char) - base - shift) % 26 + base)
        else:
            result += char
    return result

